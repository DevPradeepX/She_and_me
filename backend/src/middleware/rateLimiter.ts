import rateLimit from 'express-rate-limit';

export const readLimiter = rateLimit({
  windowMs: 15 * 60 * 1000,
  max: 200,
  standardHeaders: true,
  legacyHeaders: false,
  message: { error: 'Too many read requests, please try again later.' },
});

